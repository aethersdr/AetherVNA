#!/usr/bin/env python3
"""Generate fw/fonts.c: anti-aliased proportional fonts for the screen.

Renders printable ASCII (0x20-0x7E) from a TrueType font with ImageMagick
(`magick ... label:`), crops every glyph of a size to the rows any glyph
inks, and stores 4-bit coverage (16 levels), two pixels per byte, row by
row, with each glyph's advance width. The firmware blends each pixel
between the text and background colours.

    python3 host/mkfont.py /usr/share/fonts/noto/NotoSans-Medium.ttf > fw/fonts.c

The font used is Noto Sans Medium (SIL Open Font License 1.1, fonts/OFL.txt).
SPDX-License-Identifier: GPL-3.0-or-later (this script)"""
import subprocess, sys

SIZES = [("font_s", 11), ("font_m", 16), ("font_l", 24)]   # name, ImageMagick point size
FIRST, LAST = 0x20, 0x7E


def render(font, pt, text):
    out = subprocess.run(["magick", "-background", "black", "-fill", "white", "-font", font,
                          "-pointsize", str(pt), "label:" + text, "-depth", "8", "pgm:-"],
                         check=True, capture_output=True).stdout
    parts = out.split(b"\n", 3)                       # P5, "w h", 255, data
    w, h = map(int, parts[1].split())
    return w, h, parts[3][:w * h]


def glyphs(font, pt):
    g = {}
    for c in range(FIRST + 1, LAST + 1):
        ch = chr(c)
        text = "\\" + ch if ch in "@\\" else ch       # label: reads @file and escapes
        g[c] = render(font, pt, text)
    w2, h, _ = render(font, pt, "aa")
    w3, _, _ = render(font, pt, "a a")
    g[FIRST] = (max(1, w3 - w2), h, bytes(max(1, w3 - w2) * h))
    return g


def main():
    font = sys.argv[1]
    print("/* Generated by host/mkfont.py from %s: do not edit.\n"
          " * Noto Sans: Copyright 2022 The Noto Project Authors, SIL Open Font\n"
          " * License 1.1 (fonts/OFL.txt). 4-bit coverage, two pixels per byte. */" % font.split("/")[-1])
    print('#include "fonts.h"\n')
    for name, pt in SIZES:
        g = glyphs(font, pt)
        h = g[FIRST + 1][1]
        rows = [y for y in range(h) if any(any(g[c][2][y * g[c][0] + x] > 24 for x in range(g[c][0])) for c in g)]
        top, bot = rows[0], rows[-1] + 1
        data, offs, widths = bytearray(), [], []
        for c in range(FIRST, LAST + 1):
            w, _, px = g[c]
            offs.append(len(data)); widths.append(w)
            nib = [(px[y * w + x] * 15 + 127) // 255 for y in range(top, bot) for x in range(w)]
            if len(nib) % 2:
                nib.append(0)
            data += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
        print("static const uint8_t %s_data[%d] = {" % (name, len(data)))
        for i in range(0, len(data), 24):
            print("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
        print("};")
        print("static const uint16_t %s_offs[%d] = { %s };" % (name, len(offs), ", ".join(map(str, offs))))
        print("static const uint8_t %s_w[%d] = { %s };" % (name, len(widths), ", ".join(map(str, widths))))
        print("const font_t %s = { %d, %d, %d, %s_w, %s_offs, %s_data };\n" % (name, bot - top, FIRST, LAST, name, name, name))
        print("%s: %d px tall, %d bytes" % (name, bot - top, len(data)), file=sys.stderr)


if __name__ == "__main__":
    main()
